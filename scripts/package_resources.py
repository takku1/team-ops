"""Publish canonical research/host references inside each independently cached plugin."""
import argparse
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PLUGINS = ('team-ops', 'team-ops-delivery')
SOURCES = {
    'research-evidence.md': ROOT / 'docs/current/research-evidence.md',
    'host-compatibility.md': ROOT / 'docs/current/host-compatibility.md',
}


def expected_resources():
    for plugin in PLUGINS:
        for name, source in SOURCES.items():
            text = ('<!-- Packaged reference. Generated by scripts/package_resources.py; '
                    'edit the canonical source in the suite repository. -->\n\n'
                    + source.read_text(encoding='utf-8'))
            yield ROOT / 'plugins' / plugin / 'references' / name, text


def synchronize(check=False):
    drift = []
    for target, expected in expected_resources():
        if not target.exists() or target.read_text(encoding='utf-8') != expected:
            drift.append(str(target.relative_to(ROOT)))
            if not check:
                target.parent.mkdir(parents=True, exist_ok=True)
                target.write_text(expected, encoding='utf-8')
    return drift


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    changed = synchronize(args.check)
    print(('Out of date: ' if args.check else 'Updated: ') + ', '.join(changed) if changed else 'Package references current.')
    raise SystemExit(1 if args.check and changed else 0)
